const TONES = {
  success: { bg: colors.tealTint, fg: colors.successText },
  warning: { bg: colors.amberTint, fg: colors.amberText },
  danger: { bg: colors.redTint, fg: colors.red },
  info: { bg: colors.indigoTint, fg: colors.indigoDark },
  ai: { bg: colors.lilacTint, fg: colors.aiText },
  neutral: { bg: colors.grey100, fg: colors.textSecondary },
};

/** Colour is never the only signal: every pill carries an icon and a text label. */
export function Pill({ tone = 'neutral', icon, children, size = 'small', title }) {
  const t = TONES[tone];
  const chip = (
    <Chip
      size={size}
      icon={icon}
      label={children}
      sx={{ bgcolor: t.bg, color: t.fg, '& .MuiChip-icon': { color: t.fg }, border: `1px solid ${t.fg}22` }}
    />
  );
  return title ? <Tooltip title={title}>{chip}</Tooltip> : chip;
}

const make = (map) =>
  function Badge({ value, ...rest }) {
    const m = map[value] ?? { tone: 'neutral', label: String(value ?? '—').replace(/_/g, ' ') };
    const Icon = m.icon;
    return (
      <Pill tone={m.tone} icon={Icon ? <Icon /> : undefined} {...rest}>
        {m.label}
      </Pill>
    );
  };

