/** Lilac "AI" marker: anything generated by the model carries it. */
export function AiBadge({ label = 'AI', title = 'Generated by AI. Review before relying on it.' }) {
  return (
    <Pill tone="ai" icon={<AutoAwesomeIcon />} title={title}>
      {label}
    </Pill>
  );
}

/** Marks deterministic, rule-based output. */
export function RuleBadge({ label = 'Rule-based', title = 'Calculated by fixed rules, not by AI.' }) {
  return (
    <Pill tone="neutral" icon={<RuleIcon />} title={title}>
      {label}
    </Pill>
  );
}

export function SourceBadge({ source }) {
  if (source === 'ai') return <AiBadge />;
  if (source === 'mixed') return <AiBadge label="Rule + AI" title="Combines rule-based data with an AI estimate." />;
  return <RuleBadge />;
}
